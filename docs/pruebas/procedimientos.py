def aplicar(path):
    p = Path(path)
    text = p.read_text(encoding='utf-8')
    for num, (steps, expected) in CASOS.items():
        start = text.index('### %s ' % num)
        end = text.index('\n### ', start + 4) if '\n### ' in text[start + 4:] else len(text)
        block = text[start:end]
        for item in steps + expected:
            assert '; ' not in item and not re.search(r'(^|\s)\d+\)\s', item), (num, item)
        proc = '| Procedimiento | ' + ' '.join('%d) %s.' % (i + 1, s) for i, s in enumerate(steps)) + ' |'
        exp = '| Resultados esperados | ' + '; '.join(expected) + '. |'
        new = re.sub(r'(?m)^\| Procedimiento \| .* \|$', lambda m: proc, block, count=1)
        new = re.sub(r'(?m)^\| Resultados esperados \| .* \|$', lambda m: exp, new, count=1)
        assert new != block or (proc in block and exp in block), num
        text = text[:start] + new + text[end:]
    p.write_text(text, encoding='utf-8', newline='\n')
    return len(CASOS)


